func clipboardImage(_ pasteboard: NSPasteboard) -> Data? {
    let types = pasteboard.types ?? []
    let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    guard !privateTypes.contains(where: { types.contains(NSPasteboard.PasteboardType($0)) }),
          !types.contains(.string), !types.contains(.fileURL) else { return nil }
    if let png = pasteboard.data(forType: .png), CGImageSourceCreateWithData(png as CFData, nil) != nil { return png }
    guard let data = pasteboard.data(forType: .tiff),
          let bitmap = NSBitmapImageRep(data: data) else { return nil }
    return bitmap.representation(using: .png, properties: [:])
}

final class ClipboardStore {
    let folder: URL
    init(folder: URL) { self.folder = folder }
    func save(_ data: Data) throws {
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        let url = folder.appendingPathComponent("Clipboard-\(UUID().uuidString).png")
        try data.write(to: url, options: .atomic)
        let files = try FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: [.creationDateKey])
            .filter { $0.lastPathComponent.hasPrefix("Clipboard-") && $0.pathExtension == "png" }
            .sorted { ((try? $0.resourceValues(forKeys: [.creationDateKey]).creationDate) ?? .distantPast)
                > ((try? $1.resourceValues(forKeys: [.creationDateKey]).creationDate) ?? .distantPast) }
        for old in files.dropFirst(10) { try FileManager.default.removeItem(at: old) }
    }
    func clear(trash: (URL) throws -> Void = { try FileManager.default.trashItem(at: $0, resultingItemURL: nil) }) throws {
        guard FileManager.default.fileExists(atPath: folder.path) else { return }
        for url in try FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: nil)
            where url.lastPathComponent.hasPrefix("Clipboard-") && url.pathExtension == "png" {
            try trash(url)
        }
    }
}

func hoverScreenIndex(at point: NSPoint, frames: [NSRect], safeTops: [CGFloat] = [], widthFraction: CGFloat = 0.75) -> Int? {
    // Test each top edge directly, including its upper boundary. Adjacent displays
    // can share that boundary, so a generic contains() lookup picks the wrong one.
    frames.indices.first { index in
        let frame = frames[index]
        let inset = frame.width * (1 - min(1, max(0.1, widthFraction))) / 2
        let safeTop = safeTops.indices.contains(index) && abs(point.x - frame.midX) < 110 ? safeTops[index] : 0
        return point.x >= frame.minX + inset && point.x <= frame.maxX - inset
            && point.y >= frame.maxY - safeTop - 3 && point.y <= frame.maxY
    }
}

func shelfContainsCursor(_ point: NSPoint, panelFrame: NSRect, screenTop: CGFloat) -> Bool {
    // Include the short path from the hover edge down into the shelf.
    NSMouseInRect(point, NSRect(x: panelFrame.minX, y: panelFrame.minY, width: panelFrame.width,
           height: max(panelFrame.height, screenTop - panelFrame.minY)), false)
}

func positionedShelfFrame(on frame: NSRect, visibleFrame: NSRect, cursorX: CGFloat, count: Int = 10) -> NSRect {
    let width = min(800, visibleFrame.width - 32)
    let height = min(count > 5 ? 360 : 210, visibleFrame.height - 32)
    let x = max(visibleFrame.minX + 16, min(cursorX - width / 2, visibleFrame.maxX - width - 16))
    return NSRect(x: x, y: visibleFrame.maxY - height - 8, width: width, height: height)
}

struct DismissalState {
    var outsideSince: Date?
    mutating func shouldHide(now: Date, inside: Bool, menuOpen: Bool) -> Bool {
        if inside || menuOpen { outsideSince = nil; return false }
        outsideSince = outsideSince ?? now
        return now.timeIntervalSince(outsideSince!) >= 0.15
    }
}

struct Shot {
    let url: URL
    let date: Date
    let image: NSImage
}

func recentShots(in folder: URL, taggedOnly: Bool, limit: Int = 10) throws -> [Shot] {
    let extensions = Set(["png", "jpg", "jpeg", "heic", "tiff", "tif", "webp"])
    let files = try FileManager.default.contentsOfDirectory(at: folder,
        includingPropertiesForKeys: [.creationDateKey, .isRegularFileKey], options: [.skipsHiddenFiles])
    let candidates = files.compactMap { url -> (URL, Date)? in
        guard extensions.contains(url.pathExtension.lowercased()),
              let values = try? url.resourceValues(forKeys: [.creationDateKey, .isRegularFileKey]),
              values.isRegularFile == true else { return nil }
        if taggedOnly {
            let tagged = url.withUnsafeFileSystemRepresentation { path in
                path.map { getxattr($0, "com.apple.metadata:kMDItemIsScreenCapture", nil, 0, 0, 0) >= 0 } ?? false
            }
            if !tagged { return nil }
        }
        return (url, values.creationDate ?? .distantPast)
    }.sorted { $0.1 > $1.1 }
    return candidates.prefix(limit).compactMap { url, date in
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: 360
              ] as CFDictionary) else { return nil }
        return Shot(url: url, date: date, image: NSImage(cgImage: cg, size: .zero))
    }
}

