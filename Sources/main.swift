    @objc func clearHistory() {
        guard !clearing else { return }
        clearing = true
        clearedBefore = Date()
        UserDefaults.standard.set(clearedBefore, forKey: "clearedBefore")
        clipboardCount = NSPasteboard.general.changeCount
        UserDefaults.standard.set(clipboardCount, forKey: "lastClearedClipboardCount")
        folderShots = []; clipboardShots = []; mergeShots()
        clipboardQueue.async { [weak self] in
            guard let self else { return }
            do {
                try self.clipboardStore.clear()
                DispatchQueue.main.async { self.clearing = false; self.mergeShots() }
            } catch {
                DispatchQueue.main.async {
                    self.clearing = false; self.render()
                    let alert = NSAlert()
                    alert.messageText = "Could not move all clipboard copies to Trash"
                    alert.informativeText = error.localizedDescription
                    alert.runModal()
                }
            }
        }
    }

    @objc func toggleLogin() {
        do {
            if SMAppService.mainApp.status == .enabled {
                try SMAppService.mainApp.unregister()
            } else {
                guard Bundle.main.bundleURL.path.hasPrefix("/Applications/")
                    || Bundle.main.bundleURL.path.hasPrefix(FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Applications").path + "/") else {
                    let alert = NSAlert()
                    alert.messageText = "Move Recent Screenshots to Applications first"
                    alert.informativeText = "Quit this copy, move the app into Applications, open it there, then enable Open at login."
                    alert.runModal()
                    return
                }
                try SMAppService.mainApp.register()
                if SMAppService.mainApp.status == .requiresApproval { SMAppService.openSystemSettingsLoginItems() }
            }
            rebuildMenu()
        } catch {
            let alert = NSAlert()
            alert.messageText = "Could not change Open at login"
            alert.informativeText = error.localizedDescription
            alert.runModal()
        }
    }

    @objc func toggleClipboard() {
        clipboardEnabled.toggle()
        UserDefaults.standard.set(!clipboardEnabled, forKey: "clipboardDisabled")
        clipboardCount = NSPasteboard.general.changeCount
        rebuildMenu()
        render()
    }

    func loadClipboardHistory() {
        clipboardQueue.async { [weak self] in
            guard let self else { return }
            let images = (try? recentShots(in: self.clipboardStore.folder, taggedOnly: false)) ?? []
            DispatchQueue.main.async { self.clipboardShots = images; self.mergeShots() }
        }
    }

    func pollClipboard() {
        guard clipboardEnabled else { return }
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != clipboardCount else { return }
        clipboardCount = count
        if UserDefaults.standard.object(forKey: "lastClearedClipboardCount") != nil,
           count == UserDefaults.standard.integer(forKey: "lastClearedClipboardCount") { return }
        guard count != ownClipboardCount, let data = clipboardImage(pasteboard) else { return }
        clipboardQueue.async { [weak self] in
            guard let self else { return }
            do {
                try self.clipboardStore.save(data)
                let images = try recentShots(in: self.clipboardStore.folder, taggedOnly: false)
                DispatchQueue.main.async { self.clipboardShots = images; self.mergeShots() }
            } catch {
                DispatchQueue.main.async { self.caption.stringValue = "Could not keep copied image · \(error.localizedDescription)" }
            }
        }
    }

    func mergeShots() {
        shots = Array((folderShots + clipboardShots).filter { clearedBefore == nil || $0.date > clearedBefore! }.sorted { $0.date > $1.date }.prefix(10))
        render()
    }

    func startWatching() {
        generation += 1
        let token = generation
        let directory = folder
        let tagged = taggedOnly
        watcher?.cancel()
        watcher = nil
        caption.stringValue = "Loading screenshots…"
        DispatchQueue.global(qos: .utility).async { [weak self] in
            let result = Result { try recentShots(in: directory, taggedOnly: tagged) }
            let fd = open(directory.path, O_EVTONLY)
            DispatchQueue.main.async {
                guard let self, self.generation == token else { if fd >= 0 { close(fd) }; return }
                self.apply(result)
                guard fd >= 0 else { return }
                let source = DispatchSource.makeFileSystemObjectSource(fileDescriptor: fd,
                    eventMask: [.write, .rename, .delete], queue: .main)
                source.setEventHandler { [weak self] in self?.scheduleScan() }
                source.setCancelHandler { close(fd) }
                self.watcher = source
                source.resume()
                self.scheduleScan()
            }
        }
    }

    func scheduleScan() {
        scanWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.refresh() }
        scanWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5, execute: work)
    }

    @objc func refresh() {
        let token = generation
        let directory = folder
        let tagged = taggedOnly
        DispatchQueue.global(qos: .utility).async { [weak self] in
            let result = Result { try recentShots(in: directory, taggedOnly: tagged) }
            DispatchQueue.main.async {
                guard let self, self.generation == token else { return }
                self.apply(result)
            }
        }
    }

    func apply(_ result: Result<[Shot], Error>) {
        switch result {
        case .success(let images): folderShots = images; mergeShots()
        case .failure:
            folderShots = []; mergeShots()
        }
    }

    func render() {
        let desiredHeight: CGFloat = shots.count > 5 ? 360 : 210
        let height = min(desiredHeight, panel.screen?.visibleFrame.height ?? desiredHeight)
        if panel.frame.height != height {
            let old = panel.frame
            panel.setFrame(NSRect(x: old.minX, y: old.maxY - height, width: old.width, height: height), display: true)
        }
        clearButton?.isEnabled = !shots.isEmpty && !clearing
        for view in stack.arrangedSubviews { stack.removeArrangedSubview(view); view.removeFromSuperview() }
        caption.stringValue = shots.isEmpty ? "No screenshots yet" : "Latest \(shots.count) · Click to copy"
        caption.toolTip = clipboardEnabled ? "Take a screenshot with your mouse. Copied images appear here. Right-click an image for more actions." : "Enable Keep copied images in Controls."
        let formatter = DateFormatter()
        formatter.dateStyle = .short
        formatter.timeStyle = .short
        let cellWidth = max(60, (scroll.contentView.bounds.width - 48) / 5)
        var row: NSStackView!
        for (index, shot) in shots.enumerated() {
            if index % 5 == 0 {
                row = NSStackView()
                row.orientation = .horizontal
                row.alignment = .centerY
                row.spacing = 12
                row.distribution = .fill
                stack.addArrangedSubview(row)
            }
            let card = NSStackView()
            card.orientation = .vertical
            card.spacing = 6
            let button = ShotButton()
            button.url = shot.url
            button.image = shot.image
            button.imageScaling = .scaleProportionallyUpOrDown
            button.isBordered = false
            button.target = self
            button.action = #selector(copyShot(_:))
            button.toolTip = shot.url.lastPathComponent
            button.setAccessibilityLabel("Copy screenshot \(formatter.string(from: shot.date))")
            button.widthAnchor.constraint(equalToConstant: cellWidth).isActive = true
            button.heightAnchor.constraint(equalToConstant: 116).isActive = true
            let menu = NSMenu()
            for (title, action) in [("Copy image", #selector(copyMenu(_:))), ("Open", #selector(openShot(_:))), ("Show in Finder", #selector(revealShot(_:)))] {
                let item = menu.addItem(withTitle: title, action: action, keyEquivalent: "")
                item.target = self
                item.representedObject = shot.url
            }
            button.menu = menu
            menu.delegate = self
            card.addArrangedSubview(button)
            let label = NSTextField(labelWithString: formatter.string(from: shot.date))
            label.font = .systemFont(ofSize: 11)
            label.textColor = .secondaryLabelColor
            card.addArrangedSubview(label)
            row.addArrangedSubview(card)
        }
        stack.frame = NSRect(x: 0, y: 0, width: scroll.contentView.bounds.width, height: shots.count > 5 ? 282 : 135)
        stack.layoutSubtreeIfNeeded()
        scroll.contentView.scroll(to: .zero)
        scroll.reflectScrolledClipView(scroll.contentView)
    }

    func tick() {
        let point = NSEvent.mouseLocation
        let now = Date()
        if panel.isVisible {
            if hoverEnabled, activeMenus.isEmpty,
               let index = hoverScreenIndex(at: point, frames: NSScreen.screens.map(\.frame), safeTops: NSScreen.screens.map { $0.safeAreaInsets.top }, widthFraction: hoverWidth) {
                let screen = NSScreen.screens[index]
                if screen.frame == shelfScreenFrame && shelfContainsCursor(point, panelFrame: panel.frame, screenTop: shelfScreenTop) {
                    dismissal = DismissalState()
                    return
                }
            }
            let inside = shelfContainsCursor(point, panelFrame: panel.frame, screenTop: shelfScreenTop)
            if dismissal.shouldHide(now: now, inside: inside, menuOpen: !activeMenus.isEmpty) { hide() }
            return
        }
        guard hoverEnabled, let index = hoverScreenIndex(at: point, frames: NSScreen.screens.map(\.frame), safeTops: NSScreen.screens.map { $0.safeAreaInsets.top }, widthFraction: hoverWidth) else {
            hoverStart = nil; hoverNeedsExit = false; return
        }
        guard !hoverNeedsExit, activeMenus.isEmpty else { hoverStart = nil; return }
        let screen = NSScreen.screens[index]
        hoverStart = hoverStart ?? now
        if now.timeIntervalSince(hoverStart!) >= 0.3 {
            hoverStart = nil
            show(on: screen)
        }
    }

    func show(on screen: NSScreen) {
        panel.orderOut(nil)
        panel.setFrame(positionedShelfFrame(on: screen.frame, visibleFrame: screen.visibleFrame, cursorX: NSEvent.mouseLocation.x, count: shots.count), display: true)
        render()
        shelfScreenTop = screen.frame.maxY
        shelfScreenFrame = screen.frame
        dismissal = DismissalState()
        panel.alphaValue = 0
        panel.orderFrontRegardless()
        NSAnimationContext.runAnimationGroup { context in
            context.duration = NSWorkspace.shared.accessibilityDisplayShouldReduceMotion ? 0 : 0.15
            panel.animator().alphaValue = 1
        }
    }
    func hide() {
        panel.orderOut(nil)
        dismissal = DismissalState()
        hoverStart = nil
        hoverNeedsExit = true
    }

    func watchOutsideClicks() {
        let events: NSEvent.EventTypeMask = [.leftMouseDown, .rightMouseDown, .otherMouseDown]
        if let monitor = NSEvent.addGlobalMonitorForEvents(matching: events, handler: { [weak self] _ in
            guard let self, self.panel.isVisible else { return }
            // A click delivered to another app always dismisses our shelf.
            if !self.panel.frame.contains(NSEvent.mouseLocation) { self.hide() }
        }) { clickMonitors.append(monitor) }
        if let monitor = NSEvent.addLocalMonitorForEvents(matching: events, handler: { [weak self] event in
            guard let self, self.panel.isVisible else { return event }
            if self.activeMenus.isEmpty && !self.panel.frame.contains(NSEvent.mouseLocation) { self.hide() }
            return event
        }) { clickMonitors.append(monitor) }
        NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.didActivateApplicationNotification,
            object: nil, queue: .main) { [weak self] _ in
                guard let self, self.panel.isVisible else { return }
                self.hide()
            }
    }
    @objc func showFromMenu() {
        let point = NSEvent.mouseLocation
        if let screen = NSScreen.screens.first(where: { NSMouseInRect(point, $0.frame, false) }) ?? NSScreen.main { show(on: screen) }
    }
    @objc func toggleHover() {
        hoverEnabled.toggle()
        UserDefaults.standard.set(!hoverEnabled, forKey: "hoverDisabled")
        if !hoverEnabled { hide() }
        rebuildMenu()
    }
    @objc func chooseFolder() {
        hide()
        NSApp.activate(ignoringOtherApps: true)
        let picker = NSOpenPanel()
        picker.canChooseDirectories = true
        picker.canChooseFiles = false
        picker.allowsMultipleSelection = false
        picker.message = "Show the latest 10 images from this folder. Original files stay untouched."
        if picker.runModal() == .OK, let url = picker.url {
            folder = url; taggedOnly = false
            UserDefaults.standard.set(url.path, forKey: "folder")
            startWatching()
        }
    }
    @objc func resetFolder() {
        UserDefaults.standard.removeObject(forKey: "folder")
        let domain = "com.apple.screencapture" as CFString
        let path = (CFPreferencesCopyAppValue("location-screenshot" as CFString, domain) as? String)
            ?? (CFPreferencesCopyAppValue("location" as CFString, domain) as? String)
        folder = path.map { URL(fileURLWithPath: ($0 as NSString).expandingTildeInPath) }
            ?? FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Desktop")
        taggedOnly = folder.standardizedFileURL == FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Desktop").standardizedFileURL
        startWatching()
    }
    @objc func openFolder() { NSWorkspace.shared.open(folder) }
    @objc func copyShot(_ sender: ShotButton) { copy(sender.url) }
    @objc func copyMenu(_ sender: NSMenuItem) { if let url = sender.representedObject as? URL { copy(url) } }
    func copy(_ url: URL) {
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let isPNG = url.pathExtension.lowercased() == "png"
            let data = isPNG ? (try? Data(contentsOf: url)) : NSImage(contentsOf: url)?.tiffRepresentation
            DispatchQueue.main.async {
                guard let data else { NSSound.beep(); return }
                let item = NSPasteboardItem()
                item.setData(data, forType: isPNG ? .png : .tiff)
                NSPasteboard.general.clearContents()
                NSPasteboard.general.writeObjects([item])
                self?.ownClipboardCount = NSPasteboard.general.changeCount
                self?.hide()
            }
        }
    }
    @objc func openShot(_ sender: NSMenuItem) { if let url = sender.representedObject as? URL { NSWorkspace.shared.open(url); hide() } }
    @objc func revealShot(_ sender: NSMenuItem) { if let url = sender.representedObject as? URL { NSWorkspace.shared.activateFileViewerSelecting([url]); hide() } }
    @objc func quit() { NSApp.terminate(nil) }
    func applicationWillTerminate(_ notification: Notification) {
        watcher?.cancel(); timer?.invalidate(); clipboardTimer?.invalidate()
        for monitor in clickMonitors { NSEvent.removeMonitor(monitor) }
    }
